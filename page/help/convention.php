            <div class="m-5">
            <h2>Conditions d’inscription et d’adhésion au partenariat</h2>
            <p>
                En validant son inscription, le Partenaire reconnaît avoir lu, compris et accepté sans réserve l’ensemble des conditions ci-dessous. L’inscription ne pourra pas être finalisée sans l’acceptation expresse de ces conditions.
            </p>
            <ol class="list-decimal ml-5 space-y-3">
                <li>
                    <strong>Objet</strong><br>
                    Les présentes conditions ont pour objet de définir le cadre dans lequel le Partenaire intervient pour animer des ateliers, formations, conférences ou toute autre activité organisée par l’Association Quotidio, mieux vivre au quotidien.<br>
                    Le Partenaire intervient en qualité de professionnel indépendant, de bénévole ou dans le cadre d’un don de compétences, selon les modalités convenues pour chaque intervention. Aucun lien de subordination n’est créé entre les parties.
                </li>
                <li>
                    <strong>Modalités d’intervention</strong><br>
                    Les dates, lieux, horaires, thèmes, conditions matérielles et, le cas échéant, la rémunération de chaque intervention sont définis d’un commun accord avant chaque action.<br>
                    Le Partenaire s’engage à réaliser ses interventions avec professionnalisme et à respecter les valeurs de l’Association.
                </li>
                <li>
                    <strong>Modalités de contribution</strong><br>
                    Le Partenaire peut intervenir :
                    <ul class="list-disc ml-5">
                        <li>à titre rémunéré, sur présentation des justificatifs nécessaires et dans le respect de la réglementation en vigueur ;</li>
                        <li>à titre bénévole, sans contrepartie financière ;</li>
                        <li>à titre de don de compétences, à titre gratuit.</li>
                    </ul>
                    Quelle que soit la forme retenue, le Partenaire accepte de respecter les présentes conditions.
                </li>
                <li>
                    <strong>Respect du règlement intérieur</strong><br>
                    Le Partenaire déclare avoir pris connaissance du règlement intérieur de l’établissement accueillant les ateliers et s’engage à le respecter pendant toute la durée de ses interventions.<br>
                    Il s’engage également à respecter les règles de sécurité, d’hygiène et de fonctionnement des locaux.
                </li>
                <li>
                    <strong>Assurance</strong><br>
                    Lorsque le Partenaire intervient en qualité de professionnel, il déclare être couvert par une assurance responsabilité civile professionnelle adaptée à son activité.<br>
                    Il s’engage à maintenir cette assurance pendant toute la durée de sa collaboration avec l’Association et à en fournir une attestation sur demande.<br>
                    En cas d’intervention réalisée à titre bénévole, le Partenaire n’est tenu à aucune obligation de souscription d’assurance au titre de la présente convention.
                </li>
                <li>
                    <strong>Confidentialité</strong><br>
                    Le Partenaire s’engage à conserver strictement confidentielles toutes les informations dont il pourrait avoir connaissance dans le cadre de sa collaboration avec l’Association, notamment celles concernant les adhérents, bénéficiaires, partenaires, l’organisation interne de l’Association et toute autre information non publique.<br>
                    Cette obligation de confidentialité reste applicable après la fin de la collaboration.
                </li>
                <li>
                    <strong>Communication et droit à l’image</strong><br>
                    Le Partenaire autorise l’Association à utiliser et diffuser des photographies, vidéos ou contenus réalisés dans le cadre des ateliers, à des fins de communication, sur ses supports tels que le site internet, les réseaux sociaux, les brochures ou les newsletters.<br>
                    Le Partenaire peut demander par écrit le retrait d’un contenu pour motif légitime.
                </li>
                <li>
                    <strong>Annuaire des partenaires</strong><br>
                    En validant son inscription, le Partenaire accepte d’être référencé dans l’annuaire des partenaires de l’Association.<br>
                    Les informations susceptibles d’être publiées comprennent notamment :
                    <ul class="list-disc ml-5">
                        <li>le nom ;</li>
                        <li>l’activité ;</li>
                        <li>les coordonnées professionnelles ;</li>
                        <li>une photographie, le cas échéant ;</li>
                        <li>le site internet et les réseaux sociaux professionnels.</li>
                    </ul>
                    Le Partenaire peut demander à tout moment la mise à jour ou le retrait de ses informations.
                </li>
                <li>
                    <strong>Clause de non-sollicitation</strong><br>
                    Afin de préserver les relations développées par l’Association avec les établissements et partenaires qu’elle met en relation avec le Partenaire, celui-ci s’engage, pendant toute la durée de son inscription et pendant une période de trois (3) ans à compter de sa dernière intervention réalisée pour le compte de l’Association, à ne pas démarcher directement ou indirectement ces établissements ou partenaires en vue de leur proposer des prestations identiques, similaires ou concurrentes, sans accord écrit préalable de l’Association.<br>
                    Chaque nouvelle intervention réalisée pour le compte de l’Association fait courir un nouveau délai de trois (3) ans à compter de cette dernière intervention.<br>
                    Cette clause ne fait pas obstacle à l’exercice de l’activité professionnelle du Partenaire auprès d’autres clients ou établissements avec lesquels il n’a pas été mis en relation par l’Association.
                </li>
                <li>
                    <strong>Respect des valeurs</strong><br>
                    Le Partenaire s’engage à adopter un comportement respectueux envers les participants, les bénévoles, les salariés, les partenaires et les représentants de l’Association.<br>
                    Il s’interdit tout comportement discriminatoire, injurieux, violent ou contraire aux valeurs de l’Association.
                </li>
                <li>
                    <strong>Durée et fin de l’inscription</strong><br>
                    Les présentes conditions prennent effet à compter de la validation de l’inscription du Partenaire.<br>
                    L’inscription peut être suspendue ou supprimée par l’Association en cas de non-respect des présentes conditions, de comportement inadapté ou de faute grave.<br>
                    Les obligations de confidentialité et de non-sollicitation restent applicables après la fin de l’inscription, selon les durées prévues ci-dessus.
                </li>
                <li>
                    <strong>Litiges</strong><br>
                    En cas de différend, les parties s’engagent à rechercher une solution amiable.<br>
                    À défaut d’accord, le litige sera porté devant les juridictions territorialement compétentes.
                </li>
            </ol>
